"""Build data/curated/activating_variants.tsv for rule D4 (DD8).

ClinVar does not say whether a KCNJ11/ABCC8 variant is activating (gain of function,
causing neonatal diabetes) or inactivating (loss of function, causing congenital
hyperinsulinism). This script uses the disease ClinVar links to the variant as a proxy:

  activating  =  P/LP in some cleaned release
                 AND the disease names mention neonatal diabetes
                 AND they do NOT mention hyperinsulinism (ambiguous variants are left out)

It is a heuristic, recorded as such in the `source` column, and a limitation to state
in the paper. Hand-curated entries can be added to the file below the generated ones;
they are kept when the script is re-run (rows whose source does not start with
"ClinVar CLNDN").

    python -m scripts.curate_activating
"""

import argparse
import csv
from pathlib import Path

from app.domain import ACTIONABLE

GENES = ("KCNJ11", "ABCC8")
COLUMNS = ["chrom", "pos", "ref", "alt", "flag", "gene", "clinvar_id", "source"]
HEURISTIC = "ClinVar CLNDN"


def read_tsv(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader((ln for ln in fh if not ln.startswith("#")), delimiter="\t"))


def is_activating(disease):
    d = disease.lower()
    return "neonatal" in d and "hyperinsulin" not in d


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--clean", default="data/clean")
    ap.add_argument("--out", default="data/curated/activating_variants.tsv")
    args = ap.parse_args(argv)

    found = {}
    for path in sorted(Path(args.clean).glob("clinvar_*.panel.tsv")):  # oldest -> newest
        for r in read_tsv(path):
            if (
                r["gene"] in GENES
                and r["classification"] in ACTIONABLE
                and is_activating(r["disease"])
            ):
                key = (r["chrom"], r["pos"], r["ref"], r["alt"])
                found[key] = {
                    "chrom": r["chrom"],
                    "pos": r["pos"],
                    "ref": r["ref"],
                    "alt": r["alt"],
                    "flag": "activating",
                    "gene": r["gene"],
                    "clinvar_id": r["clinvar_id"],
                    "source": f"{HEURISTIC} neonatal diabetes, no hyperinsulinism ({path.name})",
                }
    if not found:
        raise SystemExit(f"no cleaned releases in {args.clean}; run the cleaning step first")

    out = Path(args.out)
    manual = []
    if out.exists():
        manual = [r for r in read_tsv(out) if not r["source"].startswith(HEURISTIC)]
    manual_keys = {(r["chrom"], r["pos"], r["ref"], r["alt"]) for r in manual}
    rows = [r for k, r in found.items() if k not in manual_keys] + manual
    rows.sort(key=lambda r: (r["gene"], int(r["pos"])))

    with open(out, "w", newline="") as fh:
        fh.write("# Activating KCNJ11/ABCC8 variants for rule D4 (DD8). Generated by\n")
        fh.write("# scripts/curate_activating.py; rows whose source does not start with\n")
        fh.write(f'# "{HEURISTIC}" are hand-curated and kept on re-runs.\n')
        w = csv.DictWriter(fh, COLUMNS, delimiter="\t", lineterminator="\n", extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    by_gene = {g: sum(r["gene"] == g for r in rows) for g in GENES}
    print(f"Wrote {out}: {len(rows)} variants {by_gene} ({len(manual)} hand-curated)")


if __name__ == "__main__":
    main()
