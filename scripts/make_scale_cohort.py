"""Build the scale cohort for the Stage 5 timing run (paper §5.1, "scale cohort of 10,000").

The cohort is *derived* from existing data, not generated by Synthea (DD37):

  clinical  each patient copies one of the 87 cleaned Synthea profiles (diagnosis, therapy
            periods, conditions, deceased status), drawn with replacement
  genome    each patient gets one of the 30 real 1000 Genomes backgrounds found in the
            cohort VCFs (ge_ehr_test_data_v2), i.e. ~550 real variants in the 7 genes
  carriers  CARRIER_RATE of patients also carry one rare ClinVar SNV in a panel gene,
            drawn from the start release (P/LP or VUS) and present in the newest release;
            FAMILY_SHARE of carriers have 1-3 relatives carrying the same variant

Same seed, same cohort. Output in data/synthetic/scale_<n>/:
  patients.csv diagnoses.csv medications.csv conditions.csv   (data/clean format + extras)
  backgrounds.tsv   sample chrom pos ref alt zygosity
  carriers.csv      patient_id family_id chrom pos ref alt gene start_class
  manifest.json     parameters and counts

    python -m scripts.make_scale_cohort --n 10000
"""

import argparse
import csv
import gzip
import json
import random
import uuid
from collections import Counter
from pathlib import Path

from app.domain import ACTIONABLE

ROOT = Path(__file__).resolve().parent.parent
CARRIER_RATE = 0.02
FAMILY_SHARE = 0.2
VUS_SHARE = 0.6  # carriers of a VUS vs a P/LP variant


def read_csv(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def read_release(path):
    with open(path, newline="") as fh:
        rows = csv.DictReader((ln for ln in fh if not ln.startswith("#")), delimiter="\t")
        return {(r["chrom"], r["pos"], r["ref"], r["alt"]): r for r in rows}


def zygosity(gt):
    alleles = gt.replace("|", "/").split("/")
    called = [a for a in alleles if a != "."]
    if len(called) == 1:
        return "hemizygous"
    return "homozygous" if all(a != "0" for a in called) else "heterozygous"


def load_backgrounds(cohort):
    """{1000 Genomes sample: [(chrom, pos, ref, alt, zygosity)]} from the cohort VCFs."""
    samples = {}
    for r in read_csv(cohort / "inserted_variants.csv"):
        sample = r["background_sample"]
        if not sample or sample in samples:
            continue
        recs = []
        with gzip.open(cohort / "patients" / f"{r['patient_id']}.vcf.gz", "rt") as fh:
            for line in fh:
                if line.startswith("#"):
                    continue
                c = line.rstrip("\n").split("\t")
                if "INSERTED" in c[7]:
                    continue
                recs.append((c[0], c[1], c[3], c[4], zygosity(c[9])))
        samples[sample] = recs
    return samples


def write(path, rows, fields=None):
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(
            fh,
            fields or list(rows[0]),
            lineterminator="\n",
            delimiter="\t" if path.suffix == ".tsv" else ",",
        )
        w.writeheader()
        w.writerows(rows)


def make(n, out, *, clean, cohort, start, newest, seed=11):
    rng = random.Random(seed)
    clean, cohort, out = Path(clean), Path(cohort), Path(out)
    profiles = read_csv(clean / "patients.csv")
    dx = {r["patient_id"]: r for r in read_csv(clean / "diagnoses.csv")}
    meds, conds = {}, {}
    for r in read_csv(clean / "medications.csv"):
        meds.setdefault(r["patient_id"], []).append(r)
    for r in read_csv(clean / "conditions.csv"):
        conds.setdefault(r["patient_id"], []).append(r)
    backgrounds = load_backgrounds(cohort)
    bg_keys = {k[:4] for recs in backgrounds.values() for k in recs}
    samples = sorted(backgrounds)

    old, new = read_release(start), read_release(newest)
    pool = {"P/LP": [], "VUS": []}
    for key, r in old.items():
        if key in bg_keys or key not in new or len(key[2]) != 1 or len(key[3]) != 1:
            continue
        if r["classification"] in ACTIONABLE:
            pool["P/LP"].append((key, r["gene"], r["classification"]))
        elif r["classification"] == "VUS":
            pool["VUS"].append((key, r["gene"], r["classification"]))
    for v in pool.values():
        v.sort()

    patients, diagnoses, medications, conditions = [], [], [], []
    for i in range(n):
        prof = rng.choice(profiles)
        pid = str(uuid.uuid5(uuid.NAMESPACE_URL, f"ge-ehr/scale/{seed}/{i}"))
        src = prof["patient_id"]
        patients.append(
            {
                **prof,
                "patient_id": pid,
                "profile_source": src,
                "background_sample": samples[rng.randrange(len(samples))],
                "family_id": "",
            }
        )
        d = dx.get(src)
        if d:
            diagnoses.append({**d, "patient_id": pid})
        medications += [{**m, "patient_id": pid} for m in meds.get(src, [])]
        conditions += [{**c, "patient_id": pid} for c in conds.get(src, [])]

    # Carriers: index carriers first, then relatives who share the variant.
    n_carriers = round(n * CARRIER_RATE)
    order = list(range(n))
    rng.shuffle(order)
    carriers, used, cursor, fam_no = [], set(), 0, 0
    while len(carriers) < n_carriers and cursor < n:
        kind = "VUS" if rng.random() < VUS_SHARE else "P/LP"
        key, gene, cls = rng.choice(pool[kind])
        family_size = 1 + (rng.randint(1, 3) if rng.random() < FAMILY_SHARE else 0)
        family_size = min(family_size, n_carriers - len(carriers))
        fam = f"SCALE-FAM{fam_no:04d}" if family_size > 1 else ""
        fam_no += family_size > 1
        for _ in range(family_size):
            idx = order[cursor]
            cursor += 1
            used.add(idx)
            patients[idx]["family_id"] = fam
            carriers.append(
                {
                    "patient_id": patients[idx]["patient_id"],
                    "family_id": fam,
                    "chrom": key[0],
                    "pos": key[1],
                    "ref": key[2],
                    "alt": key[3],
                    "gene": gene,
                    "start_class": cls,
                }
            )

    out.mkdir(parents=True, exist_ok=True)
    write(out / "patients.csv", patients)
    write(out / "diagnoses.csv", diagnoses)
    write(out / "medications.csv", medications)
    write(out / "conditions.csv", conditions)
    write(out / "carriers.csv", carriers)
    write(
        out / "backgrounds.tsv",
        [
            {"sample": s, "chrom": c, "pos": p, "ref": r, "alt": a, "zygosity": z}
            for s in samples
            for c, p, r, a, z in backgrounds[s]
        ],
    )
    manifest = {
        "n_patients": n,
        "seed": seed,
        "carrier_rate": CARRIER_RATE,
        "family_share": FAMILY_SHARE,
        "vus_share": VUS_SHARE,
        "start_release": Path(start).name,
        "newest_release": Path(newest).name,
        "profiles": len(profiles),
        "backgrounds": len(samples),
        "background_records": sum(len(v) for v in backgrounds.values()),
        "carriers": len(carriers),
        "families": fam_no,
        "deceased": sum(p["is_active"] == "0" for p in patients),
        "carrier_classes": Counter(c["start_class"] for c in carriers),
        "carrier_genes": Counter(c["gene"] for c in carriers),
        "note": "Derived scale cohort (DD37): Synthea profiles x 1000 Genomes backgrounds; "
        "not generated by Synthea.",
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2, default=dict) + "\n")
    return manifest


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--n", type=int, default=10_000)
    ap.add_argument("--out", default=None, help="default: data/synthetic/scale_<n>")
    ap.add_argument("--clean", default=str(ROOT / "data" / "clean"))
    ap.add_argument("--cohort", default=str(ROOT / "ge_ehr_test_data_v2"))
    ap.add_argument("--start", default=str(ROOT / "data" / "clean" / "clinvar_20230107.panel.tsv"))
    ap.add_argument("--newest", default=str(ROOT / "data" / "clean" / "clinvar_20261019.panel.tsv"))
    ap.add_argument("--seed", type=int, default=11)
    args = ap.parse_args(argv)
    out = args.out or str(ROOT / "data" / "synthetic" / f"scale_{args.n}")
    m = make(
        args.n,
        out,
        clean=args.clean,
        cohort=args.cohort,
        start=args.start,
        newest=args.newest,
        seed=args.seed,
    )
    print(
        f"Wrote {out}: {m['n_patients']:,} patients, {m['carriers']} carriers "
        f"in {m['families']} families, "
        f"{m['deceased']:,} deceased, {m['backgrounds']} backgrounds"
    )


if __name__ == "__main__":
    main()
